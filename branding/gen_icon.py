#!/usr/bin/env python3
"""Generates the Tempest logo: SVG previews plus the adaptive-icon vector drawables.

The motif is a white thermometer on a red field. The mercury ends in a small wave
instead of a flat line - the same wave the app draws for its temperature history.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "app", "src", "main", "res")

CX = 49.0          # shifted left so tube + scale ticks sit centred together
TUBE_TOP = 32.0      # centre of the rounded tube top
BULB_Y = 72.0        # centre of the bulb
OUTER_W, OUTER_R = 10.0, 13.0   # tube half-width, bulb radius
INNER_W, INNER_R = 5.5, 8.5
MERCURY_Y = 45.0
WAVE_AMP = 1.3

RED_TOP, RED_BOTTOM = "#F0483E", "#B3261E"
MERCURY_TOP, MERCURY_BOTTOM = "#F4511E", "#C62828"
GLASS = "#FFFFFF"
CHANNEL = "#FFE1DC"


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def thermometer(w, r):
    """Outline of a tube with a rounded top merged into a round bulb."""
    yj = BULB_Y - math.sqrt(r * r - w * w)  # where the tube walls meet the bulb
    l, rt = CX - w, CX + w
    return (
        f"M{f(l)},{f(yj)} L{f(l)},{f(TUBE_TOP)} "
        f"A{f(w)},{f(w)} 0 0,1 {f(rt)},{f(TUBE_TOP)} "
        f"L{f(rt)},{f(yj)} "
        f"A{f(r)},{f(r)} 0 1,1 {f(l)},{f(yj)} Z"
    )


def mercury():
    w, r = INNER_W, INNER_R
    yj = BULB_Y - math.sqrt(r * r - w * w)
    l, rt = CX - w, CX + w
    steps = 24
    wave = " ".join(
        f"L{f(l + 2 * w * i / steps)},{f(MERCURY_Y - WAVE_AMP * math.sin(2 * math.pi * i / steps))}"
        for i in range(1, steps + 1)
    )
    return (
        f"M{f(l)},{f(MERCURY_Y)} {wave} "
        f"L{f(rt)},{f(yj)} A{f(r)},{f(r)} 0 1,1 {f(l)},{f(yj)} Z"
    )


def headspace():
    """The empty part of the channel above the mercury, used as the hole in the themed icon."""
    w = INNER_W
    l, rt = CX - w, CX + w
    steps = 24
    wave = " ".join(
        f"L{f(rt - 2 * w * i / steps)},{f(MERCURY_Y - WAVE_AMP * math.sin(2 * math.pi * (steps - i) / steps))}"
        for i in range(1, steps + 1)
    )
    return (
        f"M{f(l)},{f(MERCURY_Y)} L{f(l)},{f(TUBE_TOP)} "
        f"A{f(w)},{f(w)} 0 0,1 {f(rt)},{f(TUBE_TOP)} L{f(rt)},{f(MERCURY_Y)} {wave} Z"
    )


def ticks():
    x0 = CX + OUTER_W + 4.5
    out = []
    for i, y in enumerate([28.0, 35.0, 42.0, 49.0, 56.0]):
        length = 6.0 if i % 2 == 0 else 3.6
        out.append(f"M{f(x0)},{f(y)} L{f(x0 + length)},{f(y)}")
    return " ".join(out)


TICK_W = 2.4

# ---------- SVG preview -------------------------------------------------------

def svg(mask_circle=True, mono=False):
    outer, inner, merc = thermometer(OUTER_W, OUTER_R), thermometer(INNER_W, INNER_R), mercury()
    clip = '<clipPath id="m"><circle cx="54" cy="54" r="54"/></clipPath>' if mask_circle else ""
    if mono:
        ink = "#3B2F48"
        body = (
            '<rect width="108" height="108" fill="#ECE4EE"/>'
            f'<path d="{outer} {headspace()}" fill-rule="evenodd" fill="{ink}"/>'
            f'<path d="{ticks()}" stroke="{ink}" stroke-width="{TICK_W}" stroke-linecap="round"/>'
        )
    else:
        body = (
            '<rect width="108" height="108" fill="url(#bg)"/>'
            f'<path d="{outer}" fill="{GLASS}"/>'
            f'<path d="{inner}" fill="{CHANNEL}"/>'
            f'<path d="{merc}" fill="url(#hg)"/>'
            f'<circle cx="{f(CX - 3)}" cy="{f(BULB_Y - 3)}" r="2.2" fill="#FFFFFF" fill-opacity="0.45"/>'
            f'<path d="{ticks()}" stroke="#FFFFFF" stroke-opacity="0.85" stroke-width="{TICK_W}" stroke-linecap="round"/>'
        )
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">
<defs>
  {clip}
  <linearGradient id="bg" x1="0" y1="0" x2="0.35" y2="1">
    <stop offset="0" stop-color="{RED_TOP}"/><stop offset="1" stop-color="{RED_BOTTOM}"/>
  </linearGradient>
  <linearGradient id="hg" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{MERCURY_TOP}"/><stop offset="1" stop-color="{MERCURY_BOTTOM}"/>
  </linearGradient>
</defs>
<g {'clip-path="url(#m)"' if mask_circle else ""}>{body}</g>
</svg>'''


# ---------- Android vector drawables -----------------------------------------

ANDROID = 'xmlns:android="http://schemas.android.com/apk/res/android"'
AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by branding/gen_icon.py - edit the script, not this file. -->\n'


def vector(body, aapt=False):
    ns = f"{ANDROID} {AAPT}" if aapt else ANDROID
    return f'''{HEADER}<vector {ns}
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
'''


def argb(hex_rgb, alpha="FF"):
    return "#" + alpha + hex_rgb.lstrip("#")


def linear(x1, y1, x2, y2, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return (
        '        <aapt:attr name="android:fillColor">\n'
        f'            <gradient android:type="linear" android:startX="{x1}" android:startY="{y1}" '
        f'android:endX="{x2}" android:endY="{y2}">{items}</gradient>\n'
        "        </aapt:attr>"
    )


def ticks_xml(color):
    return f'''    <path
        android:pathData="{ticks()}"
        android:strokeColor="{color}"
        android:strokeWidth="{TICK_W}"
        android:strokeLineCap="round"/>'''


def foreground_xml():
    merc_top = MERCURY_Y - WAVE_AMP
    merc_bottom = BULB_Y + INNER_R
    return vector(f'''    <path android:fillColor="{argb(GLASS)}" android:pathData="{thermometer(OUTER_W, OUTER_R)}"/>
    <path android:fillColor="{argb(CHANNEL)}" android:pathData="{thermometer(INNER_W, INNER_R)}"/>
    <path android:pathData="{mercury()}">
{linear(CX, f(merc_top), CX, f(merc_bottom), [("0", argb(MERCURY_TOP)), ("1", argb(MERCURY_BOTTOM))])}
    </path>
    <path android:fillColor="#73FFFFFF" android:pathData="M{f(CX - 3)},{f(BULB_Y - 3)}m-2.2,0a2.2,2.2 0,1 1,4.4 0a2.2,2.2 0,1 1,-4.4 0z"/>
{ticks_xml("#D9FFFFFF")}''', aapt=True)


def background_xml():
    return vector(f'''    <path android:pathData="M0,0h108v108h-108z">
{linear(0, 0, 38, 108, [("0", argb(RED_TOP)), ("1", argb(RED_BOTTOM))])}
    </path>''', aapt=True)


def monochrome_xml():
    # Themed icons tint one layer: the thermometer is one solid shape with only
    # the empty headspace above the mercury cut out (even-odd), so no seams.
    return vector(f'''    <path
        android:fillColor="#FFFFFFFF"
        android:fillType="evenOdd"
        android:pathData="{thermometer(OUTER_W, OUTER_R)} {headspace()}"/>
{ticks_xml("#FFFFFFFF")}''')


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(text)


if __name__ == "__main__":
    write(os.path.join(HERE, "logo.svg"), svg(mask_circle=False))
    write(os.path.join(HERE, "logo-round.svg"), svg(mask_circle=True))
    write(os.path.join(HERE, "logo-themed.svg"), svg(mask_circle=True, mono=True))
    write(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), foreground_xml())
    write(os.path.join(RES, "drawable", "ic_launcher_background.xml"), background_xml())
    write(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"), monochrome_xml())
    print("ok")
